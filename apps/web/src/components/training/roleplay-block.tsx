"use client";

import { useState } from "react";
import { Mic, Send } from "lucide-react";
import type { TrainingState } from "@/lib/state-machine/types";
import { Button } from "@/components/ui/button";
import { Textarea } from "@/components/ui/textarea";

export function RoleplayBlock({ state }: { state: TrainingState }) {
  const [answer, setAnswer] = useState("");
  const [submitted, setSubmitted] = useState(false);

  return (
    <div className="space-y-4">
      <div className="rounded-lg border border-slate-200 bg-slate-50 p-4">
        <div className="flex items-center gap-2 text-sm font-semibold text-slate-950">
          <Mic className="h-4 w-4 text-teal-600" />
          Roleplay prompt
        </div>
        <p className="mt-2 text-sm leading-6 text-slate-700">{state.prompt}</p>
      </div>
      <Textarea value={answer} onChange={(event) => setAnswer(event.target.value)} placeholder="Write the learner's roleplay response..." className="min-h-36 bg-white" />
      <Button onClick={() => setSubmitted(true)} disabled={!answer.trim()}>
        <Send className="h-4 w-4" />
        Submit roleplay
      </Button>
      {submitted ? (
        <div className="rounded-lg border border-teal-200 bg-teal-50 p-4 text-sm text-slate-700">
          <p className="font-semibold text-slate-950">Roleplay feedback</p>
          <p className="mt-2">Mock roleplay feedback is now generated by the state-machine engine and stored on the session.</p>
          <div className="mt-3 grid gap-2 sm:grid-cols-2">
            {state.skillTags.map((skill) => (
              <div key={skill} className="rounded-md bg-white p-3 ring-1 ring-teal-200">
                <p className="font-medium">{skill}</p>
                <p className="text-xs text-slate-500">Mock impact +2</p>
              </div>
            ))}
          </div>
        </div>
      ) : null}
    </div>
  );
}
